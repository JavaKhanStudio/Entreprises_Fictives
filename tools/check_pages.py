#!/usr/bin/env python3
"""Ask the served site what it serves: each page, and each local thing a page points at.

    python3 tools/check_pages.py [--base URL] [--render OUT_DIR]

Every tracked .html must answer 200 under the public address with its noindex and the footer
of shared/modele.html in the body, and everything a page links to or loads inside the site must
answer 200. The site is served from a sub path, so a link starting with / passes on a laptop and
breaks here: only this run sees that. The pages generated by Jekyll (README.html, CLAUDE.html)
must answer 404: they would be pages with no noindex and no footer (.nojekyll holds that).

--render looks at the served site in Chrome at 1280 and 390, and fails on a request that fails
or a console error. --base points it at a local server, to test this tool itself.
"""

import argparse
import re
import subprocess
import sys
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
PUBLIC = "https://javakhanstudio.github.io/Entreprises_Fictives/"
RENDERED = ("index.html", "merlin/index.html", "gobelin/index.html", "courtepaille/index.html", "inviolia/index.html", "dernier-prix/index.html", "source-eclat/index.html")
GENERATED = ("README.html", "CLAUDE.html")
NOINDEX = re.compile(r'<meta\s+name="robots"\s+content="noindex"\s*/?>', re.I)
FOOTER = re.compile(r"<footer\b.*?</footer>", re.I | re.S)
LOCAL = re.compile(r"""\b(?:href|src|srcset)="([^"]+)\"""", re.I)
COMMENT = re.compile(r"<!--.*?-->", re.S)


def fetch(url):
    """The status and body of url, on a redirect too (Pages must not need one here)."""
    request = urllib.request.Request(url, headers={"User-Agent": "check_pages"})
    try:
        with urllib.request.urlopen(request, timeout=30) as answer:
            return answer.status, answer.read()
    except urllib.error.HTTPError as error:
        return error.code, b""


def targets(attribute):
    """The URLs in one href, src or srcset value."""
    if "," in attribute and re.search(r"\s\d+[wx]\s*(,|$)", attribute):
        return [part.split()[0] for part in attribute.split(",") if part.strip()]
    return [attribute]


def local_targets(page_url, body, base):
    """Everything this page points at inside the site, without its fragment or query."""
    found = set()
    for attribute in LOCAL.findall(COMMENT.sub("", body)):
        for target in targets(attribute.strip()):
            if re.match(r"[a-z][a-z0-9+.-]*:", target, re.I) or target.startswith("#"):
                continue
            url = urllib.parse.urljoin(page_url, target).split("#")[0].split("?")[0]
            if url.startswith(base):
                found.add(url)
            else:
                found.add(f"OUTSIDE {url}")
    return found


def render(base, out):
    from playwright.sync_api import sync_playwright

    problems = []
    out.mkdir(parents=True, exist_ok=True)
    with sync_playwright() as playwright:
        browser = playwright.chromium.launch(channel="chrome")
        for path in RENDERED:
            for width in (1280, 390):
                # Reduced motion, as in tools/render_pages.py: Merlin's sections reveal on scroll,
                # and a full-page picture that never scrolled shows them blank (r5).
                page = browser.new_page(viewport={"width": width, "height": 800},
                                        reduced_motion="reduce")
                page.on("requestfailed", lambda r: problems.append(f"request failed: {r.url}"))
                page.on("response", lambda r: r.status >= 400
                        and problems.append(f"{r.status}: {r.url}"))
                page.on("console", lambda m: m.type == "error"
                        and problems.append(f"console: {m.text}"))
                page.goto(base + path, wait_until="networkidle")
                name = path.replace("/", "_").removesuffix(".html")
                page.screenshot(path=out / f"{name}-{width}.png", full_page=True)
                page.close()
        browser.close()
    return problems


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--base", default=PUBLIC)
    parser.add_argument("--render", type=Path)
    args = parser.parse_args()
    base = args.base.rstrip("/") + "/"

    listed = subprocess.run(["git", "ls-files", "*.html"], cwd=REPO, check=True,
                            capture_output=True, text=True).stdout.split()
    footer = FOOTER.search(COMMENT.sub("", (REPO / "shared/modele.html").read_text("utf-8"))).group()
    problems, linked = [], set()
    for path in listed:
        url = base + path
        status, raw = fetch(url)
        body = raw.decode("utf-8", "replace")
        if status != 200:
            problems.append(f"{status}: {url}")
            continue
        if not NOINDEX.search(body):
            problems.append(f"no noindex: {url}")
        if footer not in body:
            problems.append(f"footer differs: {url}")
        linked |= local_targets(url, body, base)
    for url in sorted(linked):
        if url.startswith("OUTSIDE "):
            problems.append(f"leaves the site: {url[8:]}")
        elif url.endswith("/"):
            problems.append(f"links a folder: {url}")
        elif (status := fetch(url)[0]) != 200:
            problems.append(f"{status}: {url}")
    for path in GENERATED:
        if (status := fetch(base + path)[0]) != 404:
            problems.append(f"{status} where a generated page should be 404: {base + path}")
    if args.render:
        problems += render(base, args.render)

    for problem in problems:
        print(problem)
    if problems:
        return 1
    print(f"OK: {len(listed)} pages and {len(linked)} local targets under {base}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
